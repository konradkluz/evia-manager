// @ts-check
/**
 * Renders alerts/rules.tmpl.yaml with alerts/thresholds.yaml into alerts/rules.yaml (EVM-085; architect 5: one place for
 * every threshold). Plain text substitution of ${key}; an unknown key or an unused threshold is an error.
 * Run: node infra/observability/render-rules.mjs [--check]   (--check: exit 1 when rules.yaml is stale)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = new URL('./alerts/', import.meta.url);

/** @param {string} text @returns {Record<string, string>} */
export function parseThresholds(text) {
  /** @type {Record<string, string>} */
  const out = {};
  for (const line of text.split('\n')) {
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    const match = /^([a-z][a-z0-9_]*): ([A-Za-z0-9.]+)\s*$/u.exec(line);
    if (match === null) throw new Error(`thresholds.yaml: unsupported line: ${line}`);
    const [, key = '', value = ''] = match;
    if (key in out) throw new Error(`thresholds.yaml: duplicate key ${key}`);
    out[key] = value;
  }
  return out;
}

/** @param {string} template @param {Record<string, string>} thresholds */
export function render(template, thresholds) {
  const used = new Set();
  const rendered = template.replace(/\$\{([a-z][a-z0-9_]*)\}/gu, (_, key) => {
    const value = thresholds[key];
    if (value === undefined) throw new Error(`rules.tmpl.yaml: unknown threshold ${key}`);
    used.add(key);
    return value;
  });
  const unused = Object.keys(thresholds).filter((key) => !used.has(key));
  if (unused.length > 0) throw new Error(`thresholds.yaml: unused thresholds: ${unused.join(', ')}`);
  return rendered;
}

export function renderFromDisk() {
  const thresholds = parseThresholds(readFileSync(new URL('thresholds.yaml', dir), 'utf8'));
  const header = '# GENERATED by infra/observability/render-rules.mjs from rules.tmpl.yaml and thresholds.yaml; do not edit by hand.\n';
  return header + render(readFileSync(new URL('rules.tmpl.yaml', dir), 'utf8'), thresholds);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('rules.yaml', dir);
  const rendered = renderFromDisk();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== rendered) {
      console.error('rules.yaml is stale: run node infra/observability/render-rules.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(target, rendered);
  }
}
